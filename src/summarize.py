"""Turn prediction files into metrics with bootstrap CIs and Markdown tables.

    python src/summarize.py

Reads results/predictions/*.csv and results/notebook_reproduction.json.
Writes results/summary.json and results/tables.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from corpus import CLASS_NAMES, REPO  # noqa: E402
from evaluate import bootstrap, confusion, fmt  # noqa: E402

RESULTS = REPO / "results"
PRED = RESULTS / "predictions"
MAIN_ORDER = [
    "Random Forest (notebook features)",
    "TF-IDF 1-2 gram + logistic regression",
    "TF-IDF 1-2 gram + linear SVM",
    "Lexicon features + logistic regression",
    "Length only + logistic regression",
    "DistilBERT fine-tune",
]


def load_predictions() -> pd.DataFrame:
    frames = [pd.read_csv(p) for p in sorted(PRED.glob("*.csv")) if "quick" not in p.name]
    return pd.concat(frames, ignore_index=True)


def summarize_group(g: pd.DataFrame, task: str) -> dict:
    y, p = g["y"].to_numpy(), g["pred"].to_numpy()
    k = 2 if task == "binary" else 3
    out = {"n": int(len(g)), "metrics": bootstrap(y, p, positive=1 if task == "binary" else None),
           "confusion": confusion(y, p, k),
           "per_class_recall": {CLASS_NAMES[c]: float((p[y == c] == c).mean()) for c in range(k)}}
    if g["setting"].iloc[0] == "cv":
        accs = [float((h["pred"] == h["y"]).mean()) for _, h in g.groupby("fold")]
        out["fold_accuracy"] = accs
        out["fold_accuracy_mean"] = float(np.mean(accs))
        out["fold_accuracy_std"] = float(np.std(accs, ddof=1))
        f5 = g[g["fold"] == 5]
        out["fold5_holdout"] = bootstrap(f5["y"].to_numpy(), f5["pred"].to_numpy(),
                                         positive=1 if task == "binary" else None)
    return out


def main() -> None:
    df = load_predictions()
    summary = {}
    for (task, view, setting, model), g in df.groupby(["task", "view", "setting", "model"]):
        summary.setdefault(task, {}).setdefault(view, {}).setdefault(setting, {})[model] = summarize_group(g, task)
    repro_path = RESULTS / "notebook_reproduction.json"
    repro = json.loads(repro_path.read_text()) if repro_path.exists() else None
    (RESULTS / "summary.json").write_text(json.dumps(summary, indent=1))

    lines = ["# Result tables", "",
             "Generated by `python src/summarize.py` from `results/predictions/`. "
             "Values are percentages with 95% bootstrap CIs (2,000 resamples of the pooled "
             "out-of-fold predictions). Five Ott folds, hotel-disjoint; each fold is the test set once.", ""]

    def ordered(models):
        return [m for m in MAIN_ORDER if m in models] + sorted(m for m in models if m not in MAIN_ORDER)

    # Binary
    b = summary.get("binary", {}).get("raw", {}).get("cv", {})
    lines += ["## Binary: truthful vs crowdsourced fake (Ott v1.4, n=1,600)", "",
              "Precision, recall, and F1 are for the deceptive class.", "",
              "| Model | Accuracy | Precision | Recall | F1 | Fold accuracy mean (sd) | Fold 5 held out (n=320) |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for m in ordered(b):
        s = b[m]
        mm = s["metrics"]
        lines.append(f"| {m} | {fmt(mm['accuracy'])} | {fmt(mm['precision'])} | {fmt(mm['recall'])} | "
                     f"{fmt(mm['f1'])} | {100 * s['fold_accuracy_mean']:.1f} ({100 * s['fold_accuracy_std']:.1f}) | "
                     f"{fmt(s['fold5_holdout']['accuracy'])} |")
    if repro:
        s0 = repro["seed0"]
        o = repro["other_seeds_summary"]
        lines += ["", "Notebook protocol re-run (`python src/reproduce_notebook.py`): one random 80/20 split, "
                  "n_test=320, Random Forest with the notebook's settings.", "",
                  "| Run | Test accuracy | Positive | Negative |", "| --- | --- | --- | --- |",
                  f"| Saved notebook output | 90.3 | 90.4 | 90.2 |",
                  f"| Re-run, split seed 0 | {fmt(repro['seed0_bootstrap']['accuracy'])} | "
                  f"{100 * s0['test_positive_accuracy']:.1f} | {100 * s0['test_negative_accuracy']:.1f} |",
                  f"| Re-run, split seeds 1-20 | mean {100 * o['mean']:.1f}, sd {100 * o['std']:.1f}, "
                  f"range {100 * o['min']:.1f} to {100 * o['max']:.1f} | | |"]

    # Three-way
    for view, title in (("raw", "reviews as written"), ("controlled", "prompt artifacts removed")):
        t = summary.get("three_way", {}).get(view, {}).get("cv", {})
        if not t:
            continue
        lines += ["", f"## Three-way: truthful / crowdsourced fake / LLM fake, {title} (n=2,000)", "",
                  "| Model | Accuracy | Macro precision | Macro recall | Macro F1 | Recall truthful | Recall crowdsourced | Recall LLM |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for m in ordered(t):
            s = t[m]
            mm, r = s["metrics"], s["per_class_recall"]
            lines.append(f"| {m} | {fmt(mm['accuracy'])} | {fmt(mm['macro_precision'])} | {fmt(mm['macro_recall'])} | "
                         f"{fmt(mm['macro_f1'])} | {100 * r['truthful']:.1f} | {100 * r['human_fake']:.1f} | {100 * r['llm_fake']:.1f} |")

    # Binary controlled for reference
    bc = summary.get("binary", {}).get("controlled", {}).get("cv", {})
    if bc:
        lines += ["", "## Binary task under the controlled view (first sentence, names, seed phrases removed; 60 words)", "",
                  "| Model | Accuracy | F1 (deceptive) |", "| --- | --- | --- |"]
        for m in ordered(bc):
            mm = bc[m]["metrics"]
            lines.append(f"| {m} | {fmt(mm['accuracy'])} | {fmt(mm['f1'])} |")

    # Ablations
    lines += ["", "## Feature-group ablations (logistic regression, macro F1)", "",
              "| Features | Binary, raw | Three-way, raw | Three-way, controlled |", "| --- | --- | --- | --- |"]
    abl = {(task, view): summary.get(task, {}).get(view, {}).get("ablation", {})
           for task, view in (("binary", "raw"), ("three_way", "raw"), ("three_way", "controlled"))}
    names = list(next((v for v in abl.values() if v), {}).keys())
    order = [n for n in names if not n.startswith("lexicon")] + [n for n in names if n.startswith("lexicon")]
    for n in order:
        cells = [fmt(abl[k][n]["metrics"]["macro_f1"]) if n in abl[k] else "" for k in abl]
        lines.append(f"| {n} | " + " | ".join(cells) + " |")

    # Cross-domain
    lines += ["", "## Cross-domain: train on one polarity, test on the other", "",
              "| Task | View | Model | Positive to negative: acc / macro F1 | Negative to positive: acc / macro F1 |",
              "| --- | --- | --- | --- | --- |"]
    for task in ("binary", "three_way"):
        for view in ("raw", "controlled"):
            v = summary.get(task, {}).get(view, {})
            pn, np_ = v.get("train_positive_test_negative", {}), v.get("train_negative_test_positive", {})
            for m in ordered(set(pn) | set(np_)):
                c1 = f"{fmt(pn[m]['metrics']['accuracy'])} / {fmt(pn[m]['metrics']['macro_f1'])}" if m in pn else ""
                c2 = f"{fmt(np_[m]['metrics']['accuracy'])} / {fmt(np_[m]['metrics']['macro_f1'])}" if m in np_ else ""
                lines.append(f"| {task} | {view} | {m} | {c1} | {c2} |")

    (RESULTS / "tables.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
